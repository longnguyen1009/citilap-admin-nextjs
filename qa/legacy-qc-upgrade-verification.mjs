import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { readFile } from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
const { PGlite } = createRequire(path.join(os.tmpdir(),'citilap-db-validation','package.json'))('@electric-sql/pglite');
const db = new PGlite();
const one = async (sql, params=[]) => (await db.query(sql,params)).rows[0];
try {
  await db.exec(`CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role BYPASSRLS;
    CREATE SCHEMA auth; CREATE TABLE auth.users(id uuid PRIMARY KEY);
    CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql AS $$ SELECT NULL::uuid $$;
    CREATE FUNCTION auth.role() RETURNS text LANGUAGE sql AS $$ SELECT 'authenticated'::text $$;`);
  const init = await readFile('init_full_db.sql','utf8');
  const marker = '-- MIGRATION: 20260927025849_retire_legacy_qc_workflow.sql';
  const begin = init.indexOf(marker), end = init.indexOf('INSERT INTO public.user_profiles',begin);
  assert(begin>0 && end>begin);
  await db.exec(init.slice(0,begin)+init.slice(end));
  const laptop=(await one(`SELECT receive_unknown_laptop('{"name":"Historical QC"}'::jsonb,'QA','upgrade-unknown-1') value`)).value;
  const q=(await one(`SELECT start_qc_inspection($1,'QA','upgrade-old-qc-1') value`,[laptop.id])).value;
  const items=(await db.query('SELECT check_key FROM qc_check_items WHERE qc_inspection_id=$1',[q.id])).rows.map(x=>({...x,result:'PASS',note:''}));
  assert(items.length>0);
  await one(`SELECT complete_qc_inspection($1,'PASS','ORIGINAL','ORIGINAL','A','History',$2::jsonb,'QA','upgrade-complete-1')`,[q.id,JSON.stringify(items)]);
  const snapshot=await one('SELECT to_jsonb(q) row FROM qc_inspections q WHERE id=$1',[q.id]);
  const oldItems=(await db.query('SELECT * FROM qc_check_items WHERE qc_inspection_id=$1 ORDER BY id',[q.id])).rows;
  const upgrade=await readFile('supabase/migrations/20260927025849_retire_legacy_qc_workflow.sql','utf8');
  await db.exec(upgrade);
  await db.exec(upgrade);
  assert.deepEqual(await one('SELECT to_jsonb(q) row FROM qc_inspections q WHERE id=$1',[q.id]),snapshot);
  assert.deepEqual((await db.query('SELECT * FROM qc_check_items WHERE qc_inspection_id=$1 ORDER BY id',[q.id])).rows,oldItems);
  console.log('PASS repeated incremental upgrade preserves completed QC and checklist history');
  const next=(await one(`SELECT receive_unknown_laptop('{"name":"New quick QC"}'::jsonb,'QA','upgrade-unknown-2') value`)).value;
  const quick=(await one(`SELECT start_qc_inspection($1,'QA','upgrade-new-qc-2') value`,[next.id])).value;
  assert.equal((await one('SELECT count(*)::int n FROM qc_check_items WHERE qc_inspection_id=$1',[quick.id])).n,0);
  const retry=(await one(`SELECT start_qc_inspection($1,'QA','upgrade-new-qc-retry') value`,[next.id])).value;
  assert.equal(retry.id,quick.id);
  await one(`SELECT complete_quick_qc($1,'PASS','','QA','upgrade-new-complete')`,[quick.id]);
  assert.equal((await one('SELECT status FROM laptops WHERE id=$1',[next.id])).status,'available');
  console.log('PASS new QC uses no checklist and resumes the existing active session');
} catch(e) { console.error(e.message); process.exitCode=1; } finally { await db.close(); }
