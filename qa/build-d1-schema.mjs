import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { DatabaseSync } from 'node:sqlite';

// Translate the final catalog, never regex-rewrite the PostgreSQL migration chain.
// Business functions, views and triggers require separate, explicit ports.
const catalog = JSON.parse(await readFile('docs/cloudflare/postgres-catalog.json', 'utf8'));
const quote = value => `"${value.replaceAll('"', '""')}"`;
const uuid = "(lower(hex(randomblob(4))) || '-' || lower(hex(randomblob(2))) || '-4' || substr(lower(hex(randomblob(2))),2) || '-' || substr('89ab',abs(random() % 4)+1,1) || substr(lower(hex(randomblob(2))),2) || '-' || lower(hex(randomblob(6))))";
function expression(input) {
  if (!input) return input;
  let value = input
    .replace(/::(?:character varying|timestamp with time zone|text|numeric|integer|bigint|boolean|jsonb|uuid)(?:\[\])?/g, '')
    .replace(/\bpublic\./g, '')
    .replace(/\bauth\.users\b/g, 'auth_users')
    .replace(/\bbtrim\(/g, 'trim(')
    .replace(/\btimezone\('utc', now\(\)\)/g, "(strftime('%Y-%m-%dT%H:%M:%fZ','now'))")
    .replace(/\bnow\(\)/g, "(strftime('%Y-%m-%dT%H:%M:%fZ','now'))")
    .replace(/\bgen_random_uuid\(\)/g, uuid)
    .replace(/\s+NOT VALID\b/g, '')
    .replace(/= ANY \(ARRAY\[([^\]]+)\]\)/g, 'IN ($1)')
    .replace(/<> ALL \(ARRAY\[([^\]]+)\]\)/g, 'NOT IN ($1)')
    .replace(/code ~ '\^\[A-Z0-9_-\]\{2,40\}\$'/g, "length(code) BETWEEN 2 AND 40 AND code NOT GLOB '*[^A-Z0-9_-]*'")
    .replace(/check_key ~ '\^\[a-z0-9_\]\{2,60\}\$'/g, "length(check_key) BETWEEN 2 AND 60 AND check_key NOT GLOB '*[^a-z0-9_]*'");
  if (/::|\bARRAY\[| ~ |\bnextval\(|\blpad\(/.test(value)) throw new Error(`Untranslated SQL: ${value}`);
  return value;
}
const tables = [...new Set(catalog.columns.map(column => column.table_name))];
const statements = [
  '-- Generated by node qa/build-d1-schema.mjs. Tables/constraints only; business port is tracked separately.',
  'PRAGMA foreign_keys = ON;',
  `CREATE TABLE auth_users (
    id TEXT PRIMARY KEY NOT NULL,
    email TEXT NOT NULL COLLATE NOCASE UNIQUE,
    password_hash TEXT NOT NULL,
    created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
    last_sign_in_at TEXT
  );`,
];
for (const table of tables) {
  const columns = catalog.columns.filter(column => column.table_name === table);
  const identity = columns.find(column => column.is_identity === 'YES');
  const definitions = columns.map(column => {
    const type = ['bigint', 'integer', 'smallint', 'boolean'].includes(column.data_type) ? 'INTEGER'
      : ['numeric', 'double precision', 'real'].includes(column.data_type) ? 'NUMERIC' : 'TEXT';
    let definition = `${quote(column.column_name)} ${type}`;
    if (column === identity) return `${definition} PRIMARY KEY AUTOINCREMENT`;
    if (column.is_generated === 'ALWAYS') definition += ` GENERATED ALWAYS AS (${expression(column.generation_expression)}) STORED`;
    else if (column.column_default) {
      // D1 has no sequences. Give newly created machines globally unique SKU defaults.
      definition += ` DEFAULT ${column.column_name === 'sku' && table === 'laptops'
        ? "('LT-' || upper(hex(randomblob(8))))" : expression(column.column_default)}`;
    }
    if (column.is_nullable === 'NO') definition += ' NOT NULL';
    if (column.data_type === 'boolean') definition += ` CHECK (${quote(column.column_name)} IN (0,1))`;
    if (column.data_type === 'jsonb') definition += ` CHECK (${quote(column.column_name)} IS NULL OR json_valid(${quote(column.column_name)}))`;
    return definition;
  });
  for (const constraint of catalog.constraints.filter(item => item.table_name === table)) {
    if (constraint.contype === 'p' && identity) continue;
    definitions.push(`CONSTRAINT ${quote(constraint.conname)} ${expression(constraint.definition)}`);
  }
  statements.push(`CREATE TABLE ${quote(table)} (\n  ${definitions.join(',\n  ')}\n);`);
}
const constraintNames = new Set(catalog.constraints.filter(item => ['u', 'p'].includes(item.contype)).map(item => item.conname));
for (const index of catalog.indexes) {
  if (constraintNames.has(index.indexname)) continue;
  statements.push(`${expression(index.indexdef.replace(/ USING btree/g, ''))};`);
}
const sql = `${statements.join('\n\n')}\n`;
const db = new DatabaseSync(':memory:');
try {
  db.exec(sql);
  const count = db.prepare("SELECT count(*) AS n FROM sqlite_master WHERE type='table' AND name <> 'sqlite_sequence'").get().n;
  if (count !== tables.length + 1) throw new Error(`Unexpected table count: ${count}`);
  console.log(`SQLite schema parsed: ${count} tables; ${catalog.constraints.length} source constraints processed`);
} finally { db.close(); }
await mkdir('db/d1/migrations', { recursive: true });
await writeFile('db/d1/migrations/0001_schema.sql', sql);
await mkdir('lib/cloudflare', { recursive: true });
await writeFile('lib/cloudflare/schema.json', JSON.stringify(Object.fromEntries(tables.map(table => [table,
  catalog.columns.filter(column => column.table_name === table).map(column => ({
    name: column.column_name, type: column.data_type, generated: column.is_generated === 'ALWAYS',
  })),
])), null, 2) + '\n');
const relations = catalog.constraints.filter(item => item.contype === 'f').flatMap(item => {
  const match = /^FOREIGN KEY \((\w+)\) REFERENCES (\w+)\((\w+)\)/.exec(item.definition);
  return match ? [{ name: item.conname, from: item.table_name, column: match[1], to: match[2], target: match[3] }] : [];
});
await writeFile('lib/cloudflare/relations.json', JSON.stringify(relations, null, 2) + '\n');
