import { createRequire } from 'node:module';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import assert from 'node:assert/strict';
const { chromium } = createRequire(path.join(os.tmpdir(), 'citilap-browser-qa', 'package.json'))('playwright');
const env = Object.fromEntries((await readFile('.env', 'utf8')).split(/\r?\n/).filter(line => line.includes('=') && !line.trim().startsWith('#')).map(line => { const i = line.indexOf('='); return [line.slice(0, i).trim(), line.slice(i + 1).trim().replace(/^["']|["']$/g, '')]; }));
const output = 'test-results/purchase-invoice';
const origin = process.env.APP_URL || 'http://localhost:3000';
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  await page.goto(`${origin}/login`);
  await page.locator('input[type=email]').fill(env.ADMIN_EMAIL);
  await page.locator('input[type=password]').fill(env.ADMIN_PASSWORD);
  await page.getByRole('button', { name: /đăng nhập/i }).click();
  await page.waitForURL(url => url.pathname !== '/login');
  await page.goto(`${origin}/purchases`);
  await page.locator('.purchase-day').first().waitFor({ timeout: 60000 });
  await page.locator('.route-loading-overlay').waitFor({ state: 'detached', timeout: 60000 });
  const counts = await page.locator('.purchase-day').evaluateAll(days => days.map(day => ({ tables: day.querySelectorAll('table').length, suppliers: day.querySelectorAll('.purchase-supplier').length })));
  assert.ok(counts.every(day => day.tables === 1));
  await page.locator('.purchase-supplier button').first().click();
  assert.equal(await page.locator('.purchase-draft').count(), 1);
  await page.screenshot({ path: `${output}/purchases-inline.png`, fullPage: true });
  await page.locator('.purchase-draft').getByRole('button', { name: 'Hủy', exact: true }).click();
  await page.reload();
  await page.locator('.purchase-day').first().waitFor();
  assert.equal(await page.locator('.purchase-draft').count(), 0);
  await page.goto(`${origin}/invoices`);
  const invoice = page.locator('a[href^="/invoices/"]').first();
  await invoice.waitFor({ timeout: 60000 });
  await invoice.click();
  await page.locator('.invoice-detail').waitFor({ timeout: 60000 });
  await page.getByRole('heading', { name: 'Lịch sử thanh toán' }).waitFor();
  await page.getByRole('button', { name: 'Giao diện A4', exact: true }).click();
  await page.locator('.sales-invoice-document').waitFor({ timeout: 60000 });
  await page.locator('.route-loading-overlay').waitFor({ state: 'detached', timeout: 60000 });
  assert.equal(await page.locator('.sales-invoice-document').getByRole('columnheader', { name: 'Ghi chú', exact: true }).count(), 0);
  await page.emulateMedia({ media: 'print' });
  const pdf = await page.pdf({ path: `${output}/invoice-a4.pdf`, preferCSSPageSize: true, printBackground: true, displayHeaderFooter: false });
  const pages = (pdf.toString('latin1').match(/\/Type\s*\/Page\b/g) || []).length;
  assert.equal(pages, 1, 'Current single-laptop invoice should fit on one A4 page');
  await page.screenshot({ path: `${output}/invoice-print.png`, fullPage: true });
  await page.emulateMedia({ media: 'screen' });
  await page.getByRole('button', { name: '← Chi tiết hóa đơn', exact: true }).click();
  await page.locator('.invoice-detail').waitFor();
  assert.equal(await page.locator('.sales-invoice-document').count(), 0);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(`${origin}/purchases`);
  await page.locator('.purchase-day').first().waitFor();
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'No page-level horizontal overflow');
  assert.deepEqual(errors, []);
  await writeFile(`${output}/report.json`, JSON.stringify({ counts, invoicePages: pages, errors, note: 'Read-only live data; draft cancelled without saving' }, null, 2));
  console.log(`PASS browser: ${counts.length} daily tables, inline add/cancel, A4 ${pages} page, mobile overflow, no JS errors`);
} finally { await browser.close(); }
