import { readFile, writeFile } from 'node:fs/promises';
import { DatabaseSync } from 'node:sqlite';

const catalog = JSON.parse(await readFile('docs/cloudflare/postgres-catalog.json', 'utf8'));
function translate(source) {
  return source
    .replace(/::(?:timestamp with time zone|character varying|numeric(?:\(\d+,\d+\))?|text|bigint|integer|boolean)/g, '')
    .replace(/= ANY \(ARRAY\[([^\]]+)\]\)/g, 'IN ($1)')
    .replace(/<> ALL \(ARRAY\[([^\]]+)\]\)/g, 'NOT IN ($1)')
    .replace(/\bGREATEST\(/g, 'max(')
    .replace(/\bnow\(\)/g, "(strftime('%Y-%m-%dT%H:%M:%fZ','now'))")
    .replace(/to_char\(\(b.purchase_date\), 'MM\/YYYY'\)/g, "strftime('%m/%Y',b.purchase_date)");
}
const statements = [];
for (const view of catalog.views) {
  let source = view.definition;
  if (view.name === 'cash_account_balances') {
    // SQLite has no LATERAL JOIN. Rank reconciliations once, preserving one row per account.
    source = source.replace(/LEFT JOIN LATERAL \([\s\S]*?\) r ON \(true\)/,
      `LEFT JOIN (SELECT account_id,reconciled_at AS last_reconciled_at,difference AS last_difference,
        row_number() OVER (PARTITION BY account_id ORDER BY reconciled_at DESC,id DESC) AS position
        FROM account_reconciliations) r ON (r.account_id=a.id AND r.position=1)`);
  }
  if (view.name === 'customer_receivable_summaries') {
    source = source.replace(/\(o.payment_due_at >= now\(\)\)/g, '(julianday(o.payment_due_at) >= julianday(\'now\'))')
      .replace(/\(\(now\(\) - o.payment_due_at\) <= '(\d+) days'::interval\)/g, "(julianday('now') - julianday(o.payment_due_at) <= $1)");
  }
  source = translate(source);
  if (view.name === 'laptop_landed_costs') {
    source = source.replace(/array_remove\(ARRAY\[([\s\S]*?)\], NULL\) AS reasons/,
      '(SELECT json_group_array(value) FROM json_each(json_array($1)) WHERE value IS NOT NULL) AS reasons');
  }
  if (view.name === 'unified_inventory') source = source.replace('(l.id) AS entity_key', 'CAST(l.id AS TEXT) AS entity_key');
  if (/::|\bARRAY\[|LATERAL|to_char|array_remove/.test(source)) throw new Error(`Untranslated view: ${view.name}`);
  statements.push(`CREATE VIEW ${view.name} AS\n${source.trim()}`);
}
const sql = '-- Generated by node qa/build-d1-views.mjs from the final PostgreSQL catalog.\n\n' + statements.join('\n\n') + '\n';
const db = new DatabaseSync(':memory:');
try {
  db.exec(await readFile('db/d1/migrations/0001_schema.sql', 'utf8'));
  db.exec(sql);
  for (const view of catalog.views) db.prepare(`SELECT * FROM ${view.name} LIMIT 1`).all();
  console.log(`PASS ${catalog.views.length} D1 views: parsed and queried`);
} finally { db.close(); }
await writeFile('db/d1/migrations/0003_views.sql', sql);
