import { createRequire } from 'node:module';
import { readFile } from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import assert from 'node:assert/strict';

const requireFromTemp = createRequire(path.join(os.tmpdir(), 'citilap-db-validation', 'package.json'));
const { PGlite } = requireFromTemp('@electric-sql/pglite');
const db = new PGlite();
await db.exec(`
  CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role;
  CREATE TABLE orders(
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_price numeric NOT NULL DEFAULT 0,
    amount_paid numeric NOT NULL DEFAULT 0,
    debt_amount numeric NOT NULL DEFAULT 0,
    trade_in_credit_vnd numeric(18,2) NOT NULL DEFAULT 0,
    payment_status text NOT NULL DEFAULT 'unpaid'
  );
  CREATE TABLE payments(
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint REFERENCES orders(id), payment_type text, amount numeric,
    payment_date date DEFAULT current_date
  );
  CREATE TABLE financial_records(
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint REFERENCES orders(id), occurred_on date DEFAULT current_date
  );
  CREATE TABLE invoices(
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint UNIQUE REFERENCES orders(id), snapshot jsonb NOT NULL
  );
  INSERT INTO orders(sale_price,amount_paid,debt_amount,trade_in_credit_vnd,payment_status)
  VALUES(30,5,25,10000000,'deposited');
`);

let migration = await readFile('db/migrations/20261013_phase9_trade_in_obligation_repair.sql', 'utf8');
migration = migration.replace(/^\s*(?:GRANT|REVOKE)\b[\s\S]*?;\s*$/gmi, '');
migration = migration.split(/\r?\n/).filter(line => !/^\s*(GRANT|REVOKE|FROM PUBLIC)/i.test(line)).join('\n');
await db.exec(migration);

const one = async sql => (await db.query(sql)).rows[0];
assert.equal(Number((await one('SELECT debt_amount FROM orders WHERE id=1')).debt_amount), 15);
await db.exec("UPDATE orders SET amount_paid=15,payment_status='deposited' WHERE id=1");
const paid = await one('SELECT debt_amount,payment_status FROM orders WHERE id=1');
assert.equal(Number(paid.debt_amount), 5);
assert.equal(paid.payment_status, 'deposited');

let rejected = false;
try { await db.exec('UPDATE orders SET amount_paid=25 WHERE id=1'); } catch (error) { rejected = /vượt giá bán/.test(error.message); }
assert(rejected, 'Database must reject cash plus trade-in credit above the sale price');

await db.exec(`
  INSERT INTO payments(order_id,payment_type,amount) VALUES(1,'balance',15);
  INSERT INTO invoices(order_id,snapshot) VALUES(1,'{"order":{},"payments":[],"financial_records":[]}');
  SELECT sync_invoice_payment_snapshot(1);
`);
const invoice = await one('SELECT snapshot FROM invoices WHERE order_id=1');
assert.equal(Number(invoice.snapshot.order.debt_amount), 5);
assert.equal(Number(invoice.snapshot.order.trade_in_credit_vnd), 10000000);
