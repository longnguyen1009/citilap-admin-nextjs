import { createRequire } from 'node:module';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';

const { PGlite } = createRequire(path.join(os.tmpdir(), 'citilap-db-validation', 'package.json'))('@electric-sql/pglite');
const db = new PGlite();
const qi = value => `"${String(value).replaceAll('"', '""')}"`;
const ql = value => value === null ? 'NULL' : `'${String(value).replaceAll("'", "''")}'`;
const rows = async (sql, params = []) => (await db.query(sql, params)).rows;
const section = (title, statements) => statements.length ? `\n-- ${title}\n${statements.join('\n')}\n` : '';

try {
  await db.exec(`CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role BYPASSRLS;
    CREATE SCHEMA auth; CREATE TABLE auth.users(id uuid PRIMARY KEY);
    CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql AS $$ SELECT NULL::uuid $$;
    CREATE FUNCTION auth.role() RETURNS text LANGUAGE sql AS $$ SELECT 'authenticated'::text $$;`);
  await db.exec(await readFile('init_full_db.sql', 'utf8'));

  const tables = await rows(`SELECT c.oid,c.relname,c.relrowsecurity
    FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
    WHERE n.nspname='public' AND c.relkind IN('r','p') ORDER BY c.relname`);
  const sequences = await rows(`SELECT c.oid,c.relname
    FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
    WHERE n.nspname='public' AND c.relkind='S'
      AND NOT EXISTS(SELECT 1 FROM pg_depend d WHERE d.objid=c.oid AND d.deptype='i')
    ORDER BY c.relname`);

  const sequenceSql = sequences.map(sequence => `CREATE SEQUENCE public.${qi(sequence.relname)};`);
  const tableSql = [];
  for (const table of tables) {
    const columns = await rows(`SELECT a.attname,format_type(a.atttypid,a.atttypmod) data_type,
      a.attnotnull,a.attidentity,a.attgenerated,pg_get_expr(d.adbin,d.adrelid) default_expr
      FROM pg_attribute a LEFT JOIN pg_attrdef d ON d.adrelid=a.attrelid AND d.adnum=a.attnum
      WHERE a.attrelid=$1 AND a.attnum>0 AND NOT a.attisdropped ORDER BY a.attnum`, [table.oid]);
    const definitions = columns.map(column => {
      let definition = `${qi(column.attname)} ${column.data_type}`;
      if (column.attidentity === 'a') definition += ' GENERATED ALWAYS AS IDENTITY';
      else if (column.attidentity === 'd') definition += ' GENERATED BY DEFAULT AS IDENTITY';
      else if (column.attgenerated === 's') definition += ` GENERATED ALWAYS AS (${column.default_expr}) STORED`;
      else if (column.default_expr) definition += ` DEFAULT ${column.default_expr}`;
      if (column.attnotnull) definition += ' NOT NULL';
      return `  ${definition}`;
    });
    tableSql.push(`CREATE TABLE public.${qi(table.relname)} (\n${definitions.join(',\n')}\n);`);
  }

  const constraints = await rows(`SELECT c.conname,t.relname,pg_get_constraintdef(c.oid,true) definition,
      CASE c.contype WHEN 'p' THEN 1 WHEN 'u' THEN 2 WHEN 'c' THEN 3 WHEN 'f' THEN 4 ELSE 5 END sort_order
    FROM pg_constraint c JOIN pg_class t ON t.oid=c.conrelid JOIN pg_namespace n ON n.oid=t.relnamespace
    WHERE n.nspname='public'
      AND c.contype <> 'n'
    ORDER BY sort_order,t.relname,c.conname`);
  const constraintSql = constraints.map(constraint =>
    `ALTER TABLE public.${qi(constraint.relname)} ADD CONSTRAINT ${qi(constraint.conname)} ${constraint.definition};`);

  const indexes = await rows(`SELECT pg_get_indexdef(i.indexrelid) definition
    FROM pg_index i JOIN pg_class t ON t.oid=i.indrelid JOIN pg_namespace n ON n.oid=t.relnamespace
    WHERE n.nspname='public' AND NOT i.indisprimary
      AND NOT EXISTS(SELECT 1 FROM pg_constraint c WHERE c.conindid=i.indexrelid)
    ORDER BY t.relname,(SELECT relname FROM pg_class WHERE oid=i.indexrelid)`);
  const indexSql = indexes.map(index => `${index.definition};`);

  const functions = await rows(`SELECT p.oid,p.proname,
      p.proname||'('||pg_get_function_identity_arguments(p.oid)||')' signature,
      pg_get_functiondef(p.oid) definition
    FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace
    WHERE n.nspname='public' ORDER BY p.oid`);
  const obsoleteNames = new Set([
    'update_purchase_draft', 'transition_purchase_batch', 'next_shipment_code',
    'create_shipment', 'transition_shipment', 'receive_shipment_items',
    'resolve_receiving_exception', 'guard_laptop_qc_transition',
    'create_cost_allocation', 'guard_finalized_cost_history',
    'guard_allocated_shipment_cost_source', 'guard_allocated_shipment_item',
    'refresh_direct_batch_status', 'create_direct_purchase', 'receive_direct_items',
    'match_unmatched_intake', 'ignore_direct_purchase_item', 'inventory_display_status',
  ]);
  const obsoleteFunctions = functions.filter(fn => obsoleteNames.has(fn.proname));
  const activeFunctions = functions.filter(fn => !obsoleteNames.has(fn.proname));
  const obsoleteFunctionOids = new Set(obsoleteFunctions.map(fn => String(fn.oid)));
  const functionSql = activeFunctions.map(fn => fn.definition.trim().replace(/;?$/, ';'));

  const views = await rows(`SELECT c.oid,c.relname,c.relkind,pg_get_viewdef(c.oid,true) definition
    FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
    WHERE n.nspname='public' AND c.relkind IN('v','m') ORDER BY c.oid`);
  const viewSql = views.map(view => `${view.relkind === 'm' ? 'CREATE MATERIALIZED VIEW' : 'CREATE VIEW'} public.${qi(view.relname)} AS\n${view.definition};`);

  const triggers = await rows(`SELECT t.tgfoid,pg_get_triggerdef(t.oid,true) definition
    FROM pg_trigger t JOIN pg_class c ON c.oid=t.tgrelid JOIN pg_namespace n ON n.oid=c.relnamespace
    WHERE n.nspname='public' AND NOT t.tgisinternal ORDER BY c.relname,t.tgname`);
  const activeTriggers = triggers.filter(trigger => !obsoleteFunctionOids.has(String(trigger.tgfoid)));
  const triggerSql = activeTriggers.map(trigger => `${trigger.definition};`);

  const rlsSql = tables.filter(table => table.relrowsecurity)
    .map(table => `ALTER TABLE public.${qi(table.relname)} ENABLE ROW LEVEL SECURITY;`);
  const policies = await rows(`SELECT tablename,policyname,permissive,roles,cmd,qual,with_check
    FROM pg_policies WHERE schemaname='public' ORDER BY tablename,policyname`);
  const policySql = policies.map(policy => {
    const roles = policy.roles?.length ? policy.roles.map(role => role === 'public' ? 'PUBLIC' : qi(role)).join(', ') : 'PUBLIC';
    return `CREATE POLICY ${qi(policy.policyname)} ON public.${qi(policy.tablename)} AS ${policy.permissive} FOR ${policy.cmd} TO ${roles}`
      + (policy.qual ? ` USING (${policy.qual})` : '')
      + (policy.with_check ? ` WITH CHECK (${policy.with_check})` : '') + ';';
  });

  const appOptions = await rows(`SELECT group_key,option_key,label,is_active,sort_order FROM app_options ORDER BY id`);
  const accessories = await rows(`SELECT sku,name,kind,price,note,active FROM accessories ORDER BY id`);
  const seedSql = [];
  if (appOptions.length) seedSql.push(`INSERT INTO public.app_options(group_key,option_key,label,is_active,sort_order) VALUES\n${appOptions.map(row =>
    `  (${ql(row.group_key)},${ql(row.option_key)},${ql(row.label)},${row.is_active ? 'true' : 'false'},${Number(row.sort_order)})`).join(',\n')};`);
  if (accessories.length) seedSql.push(`INSERT INTO public.accessories(sku,name,kind,price,note,active) VALUES\n${accessories.map(row =>
    `  (${ql(row.sku)},${ql(row.name)},${ql(row.kind)},${Number(row.price)},${ql(row.note)},${row.active ? 'true' : 'false'})`).join(',\n')};`);

  const sql = `-- CitiLap clean baseline. Generated from the verified final public catalog.\n`
    + `-- Destructive for public only; auth and Supabase system schemas are preserved.\nBEGIN;\nDROP SCHEMA IF EXISTS public CASCADE;\nCREATE SCHEMA public;\nGRANT ALL ON SCHEMA public TO postgres,service_role;\n`
    + section('SEQUENCES', sequenceSql)
    + section('TABLES', tableSql)
    + section('CONSTRAINTS', constraintSql)
    + section('INDEXES', indexSql)
    + section('VIEWS', viewSql)
    + section('FUNCTIONS', functionSql)
    + section('TRIGGERS', triggerSql)
    + section('ROW LEVEL SECURITY', [...rlsSql, ...policySql])
    + section('MINIMUM CONFIGURATION SEED', seedSql)
    + `\nREVOKE ALL ON ALL TABLES IN SCHEMA public FROM PUBLIC,anon,authenticated;\n`
    + `REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM PUBLIC,anon,authenticated;\n`
    + `REVOKE ALL ON ALL FUNCTIONS IN SCHEMA public FROM PUBLIC,anon,authenticated;\n`
    + `REVOKE ALL ON SCHEMA public FROM PUBLIC,anon,authenticated;\n`
    + `GRANT USAGE ON SCHEMA public TO authenticated;\n`
    + `GRANT SELECT ON public.user_profiles TO authenticated;\n`
    + `GRANT ALL ON ALL TABLES IN SCHEMA public TO service_role;\n`
    + `GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO service_role;\n`
    + `GRANT EXECUTE ON ALL FUNCTIONS IN SCHEMA public TO service_role;\n`
    + `NOTIFY pgrst,'reload schema';\nCOMMIT;\n`;

  await writeFile('db/20260925_clean_baseline.generated.sql', sql);
  await writeFile('db/obsolete-functions.generated.txt', obsoleteFunctions.map(fn => fn.signature).join('\n') + '\n');
  console.log(`Generated clean baseline: ${tables.length} tables, ${activeFunctions.length} functions, ${views.length} views; omitted ${obsoleteFunctions.length} obsolete functions.`);
} finally {
  await db.close();
}
