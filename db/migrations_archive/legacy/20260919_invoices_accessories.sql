CREATE OR REPLACE FUNCTION public.save_order_invoice_fields(p_order jsonb, p_result jsonb)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE v_id bigint := (p_result->'order'->>'id')::bigint; v_row orders%ROWTYPE;
BEGIN
 IF p_order ? 'gift_accessory_ids' AND (jsonb_typeof(p_order->'gift_accessory_ids') <> 'array' OR jsonb_array_length(p_order->'gift_accessory_ids') > 30) THEN
   RAISE EXCEPTION 'Danh sách quà tặng không hợp lệ';
 END IF;
 IF p_order ? 'gift_accessory_ids' AND EXISTS (
   SELECT 1 FROM jsonb_array_elements_text(p_order->'gift_accessory_ids') x(id)
   WHERE NOT EXISTS (SELECT 1 FROM accessories a WHERE a.id::text = x.id AND a.active)
 ) THEN RAISE EXCEPTION 'Phụ kiện không tồn tại hoặc đã ngừng sử dụng'; END IF;
 UPDATE orders SET
   branch_id = CASE WHEN p_order ? 'branch_id' THEN (p_order->>'branch_id')::bigint ELSE branch_id END,
   gift_accessory_ids = CASE WHEN p_order ? 'gift_accessory_ids' THEN p_order->'gift_accessory_ids' ELSE gift_accessory_ids END,
   gift_preset = CASE WHEN p_order ? 'gift_preset' THEN coalesce(p_order->>'gift_preset','') ELSE gift_preset END
 WHERE id = v_id RETURNING * INTO v_row;
 RETURN jsonb_set(p_result,'{order}',to_jsonb(v_row));
END $$;
