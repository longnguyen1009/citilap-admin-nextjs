CREATE OR REPLACE FUNCTION public.issue_invoice(p_order_id bigint,p_actor text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE o orders%ROWTYPE; l laptops%ROWTYPE; c customers%ROWTYPE; b branches%ROWTYPE;
 i invoices%ROWTYPE; items jsonb; receipts jsonb; finance jsonb; ledger_total numeric; effective_paid numeric; deposit_total numeric; a accessories%ROWTYPE;
BEGIN
 SELECT * INTO o FROM orders WHERE id=p_order_id FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'Không tìm thấy đơn hàng'; END IF;
 SELECT * INTO i FROM invoices WHERE order_id=p_order_id;
 IF FOUND THEN RETURN to_jsonb(i); END IF;
 IF o.is_active IS NOT TRUE OR o.order_status NOT IN ('shipping','done') THEN
   RAISE EXCEPTION 'Chỉ xuất hóa đơn khi đơn đang giao hàng hoặc đã hoàn thành';
 END IF;
 IF coalesce(o.sale_price,0) <= 0 THEN
   RAISE EXCEPTION 'Đơn hàng chưa có giá bán hợp lệ';
 END IF;
 SELECT * INTO b FROM branches WHERE id=o.branch_id;
 IF NOT FOUND THEN RAISE EXCEPTION 'Vui lòng chọn chi nhánh bán hàng trong đơn'; END IF;
 SELECT * INTO l FROM laptops WHERE id=o.laptop_id FOR SHARE;
 IF NOT FOUND THEN RAISE EXCEPTION 'Đơn chưa có laptop'; END IF;
 SELECT * INTO c FROM customers WHERE id=o.customer_id;
 IF NOT FOUND THEN RAISE EXCEPTION 'Vui lòng chọn khách hàng có tên, SĐT và địa chỉ'; END IF;
 IF coalesce(btrim(c.name),'')='' OR coalesce(btrim(c.phone),'')='' THEN RAISE EXCEPTION 'Khách hàng thiếu tên hoặc số điện thoại'; END IF;
 SELECT coalesce(jsonb_agg(to_jsonb(p) ORDER BY p.payment_date,p.id),'[]'),
 coalesce(sum(CASE WHEN p.payment_type='refund' THEN -p.amount ELSE p.amount END),0),
 coalesce(sum(CASE WHEN p.payment_type='deposit' THEN p.amount ELSE 0 END),0)
 INTO receipts,ledger_total,deposit_total FROM payments p WHERE p.order_id=o.id;
 effective_paid := greatest(ledger_total,coalesce(o.amount_paid,0));
 IF (deposit_total <= 0 AND coalesce(o.deposit_amount,0) <= 0
     AND NOT (o.payment_status='paid' AND coalesce(o.amount_paid,0) > 0))
    OR effective_paid <= 0 THEN
   RAISE EXCEPTION 'Cần ghi nhận ít nhất một khoản đặt cọc trước khi xuất hóa đơn';
 END IF;
 SELECT coalesce(jsonb_agg(to_jsonb(f) ORDER BY f.occurred_on,f.id),'[]') INTO finance FROM financial_records f WHERE f.order_id=o.id;
 items := jsonb_build_array(jsonb_build_object('kind','laptop','id',l.id,'sku',l.sku,'name',l.name,'quantity',1,'price',o.sale_price,'total',o.sale_price,'serial',l.serial,'note',concat_ws(' · ',l.condition_note,o.warranty,o.setup_note)));
 FOR a IN SELECT * FROM accessories WHERE id IN (SELECT value::bigint FROM jsonb_array_elements_text(o.gift_accessory_ids)) ORDER BY id LOOP
   items := items || jsonb_build_array(jsonb_build_object('kind','gift','id',a.id,'sku',a.sku,'name',a.name,'quantity',1,'price',0,'total',0,'serial','','note',a.note));
 END LOOP;
 INSERT INTO invoices(order_id,laptop_id,customer_id,created_by,snapshot) VALUES
 (o.id,l.id,c.id,p_actor,jsonb_build_object('order',to_jsonb(o),'customer',to_jsonb(c),'branch',to_jsonb(b),'items',items,'payments',receipts,'financial_records',finance,'total',o.sale_price,'paid',effective_paid,'currency','VND','unit_multiplier',1000000)) RETURNING * INTO i;
 RETURN to_jsonb(i);
END $$;

-- Chỉ khối thanh toán được đồng bộ sau khi phát hành. Thông tin khách hàng,
-- sản phẩm, giá bán và quà tặng vẫn là snapshot bất biến.
CREATE OR REPLACE FUNCTION public.sync_invoice_payment_snapshot(p_order_id bigint)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE receipts jsonb; finance jsonb; ledger_total numeric; effective_paid numeric; payment_count bigint; current_order orders%ROWTYPE;
BEGIN
 SELECT * INTO current_order FROM orders WHERE id=p_order_id;
 IF NOT FOUND OR NOT EXISTS (SELECT 1 FROM invoices WHERE order_id=p_order_id) THEN RETURN; END IF;
 SELECT coalesce(jsonb_agg(to_jsonb(p) ORDER BY p.payment_date,p.id),'[]'),
        coalesce(sum(CASE WHEN p.payment_type='refund' THEN -p.amount ELSE p.amount END),0),
        count(*)
 INTO receipts,ledger_total,payment_count FROM payments p WHERE p.order_id=p_order_id;
 -- Orders created before the payment ledger retain their trustworthy aggregate.
 -- Once ledger rows exist, the ledger becomes the single source of truth.
 effective_paid := CASE WHEN payment_count > 0 THEN ledger_total ELSE coalesce(current_order.amount_paid,0) END;
 SELECT coalesce(jsonb_agg(to_jsonb(f) ORDER BY f.occurred_on,f.id),'[]')
 INTO finance FROM financial_records f WHERE f.order_id=p_order_id;
 UPDATE invoices SET snapshot = jsonb_set(
   jsonb_set(
     jsonb_set(
       jsonb_set(
         jsonb_set(
           jsonb_set(snapshot,'{payments}',receipts,true),
           '{financial_records}',finance,true),
         '{paid}',to_jsonb(effective_paid),true),
       '{order,payment_status}',to_jsonb(current_order.payment_status),true),
     '{order,amount_paid}',to_jsonb(coalesce(current_order.amount_paid,ledger_total)),true),
   '{order,debt_amount}',to_jsonb(greatest(coalesce(current_order.sale_price,0)-effective_paid,0)),true)
 WHERE order_id=p_order_id;
END $$;

CREATE OR REPLACE FUNCTION public.sync_invoice_payment_trigger()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
BEGIN
 IF TG_OP = 'DELETE' THEN
   PERFORM sync_invoice_payment_snapshot(OLD.order_id);
   RETURN OLD;
 END IF;
 PERFORM sync_invoice_payment_snapshot(NEW.order_id);
 RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS invoices_sync_from_payments ON public.payments;
CREATE TRIGGER invoices_sync_from_payments AFTER INSERT OR UPDATE OR DELETE ON public.payments
FOR EACH ROW EXECUTE FUNCTION public.sync_invoice_payment_trigger();

DROP TRIGGER IF EXISTS invoices_sync_from_financial_records ON public.financial_records;
CREATE TRIGGER invoices_sync_from_financial_records AFTER INSERT OR UPDATE OR DELETE ON public.financial_records
FOR EACH ROW EXECUTE FUNCTION public.sync_invoice_payment_trigger();

CREATE OR REPLACE FUNCTION public.sync_invoice_order_payment_trigger()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
BEGIN PERFORM sync_invoice_payment_snapshot(NEW.id); RETURN NEW; END $$;

