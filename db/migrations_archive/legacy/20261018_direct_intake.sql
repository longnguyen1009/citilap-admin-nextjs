CREATE OR REPLACE FUNCTION public.inventory_display_status(p_laptop_id bigint,p_backend_status text,p_is_active boolean,p_is_locked boolean)
RETURNS text LANGUAGE sql STABLE SET search_path=public,pg_temp AS $$
 SELECT CASE
  WHEN p_is_active IS NOT TRUE OR p_backend_status='skipped' THEN 'skipped'
  WHEN p_backend_status='sold' OR EXISTS(SELECT 1 FROM orders o WHERE o.laptop_id=p_laptop_id AND o.is_active AND o.order_status='done') THEN 'sold'
  WHEN p_backend_status='returned_cn' OR EXISTS(SELECT 1 FROM supplier_return_items r WHERE r.laptop_id=p_laptop_id AND r.status NOT IN('CANCELLED','REJECTED','REFUNDED','REPLACED')) THEN 'returned_cn'
  WHEN p_backend_status IN('repair','repairing') OR EXISTS(SELECT 1 FROM repair_jobs r WHERE r.laptop_id=p_laptop_id AND r.status NOT IN('COMPLETED','CANCELLED')) THEN 'repairing'
  WHEN p_backend_status IN('waiting_qc','qc_in_progress','qc_failed') THEN 'waiting_qc'
  WHEN p_backend_status='deposited' OR EXISTS(SELECT 1 FROM orders o WHERE (o.laptop_id=p_laptop_id OR o.requested_laptop_id=p_laptop_id) AND o.is_active AND (o.order_status='deposited' OR o.payment_status='deposited')) THEN 'deposited'
  ELSE 'available' END
$$;

