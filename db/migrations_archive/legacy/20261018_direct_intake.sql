CREATE VIEW public.purchase_batch_summaries AS
SELECT b.*,(CASE WHEN b.procurement_flow='DIRECT' THEN coalesce(i.purchase_total_rmb,b.subtotal_rmb)
 ELSE b.subtotal_rmb+b.domestic_shipping_rmb+b.other_cost_rmb END)::numeric(14,2) total_rmb,
 coalesce(p.paid_rmb,0)::numeric(14,2) paid_rmb,
 greatest(CASE WHEN b.procurement_flow='DIRECT' THEN coalesce(i.purchase_total_rmb,b.subtotal_rmb)
 ELSE b.subtotal_rmb+b.domestic_shipping_rmb+b.other_cost_rmb END-coalesce(p.paid_rmb,0),0)::numeric(14,2) debt_rmb,
 coalesce(i.item_count,0)::bigint item_count,coalesce(i.received_count,0)::bigint received_count,
 coalesce(i.pending_count,0)::bigint pending_count,coalesce(i.ignored_count,0)::bigint ignored_count,
 coalesce(i.purchase_total_rmb,0)::numeric(14,2) purchase_total_rmb,
 coalesce(i.shipping_total_rmb,0)::numeric(14,2) shipping_total_rmb,s.code supplier_code,s.name supplier_name
FROM purchase_batches b JOIN suppliers s ON s.id=b.supplier_id
LEFT JOIN (SELECT purchase_batch_id,sum(amount_rmb) paid_rmb FROM supplier_payments GROUP BY purchase_batch_id) p ON p.purchase_batch_id=b.id
LEFT JOIN (SELECT purchase_batch_id,count(*) FILTER(WHERE status<>'CANCELLED' OR ignored_at IS NOT NULL) item_count,
 count(*) FILTER(WHERE received_at IS NOT NULL) received_count,
 count(*) FILTER(WHERE received_at IS NULL AND ignored_at IS NULL AND status<>'CANCELLED') pending_count,
 count(*) FILTER(WHERE ignored_at IS NOT NULL) ignored_count,sum(purchase_price_rmb) FILTER(WHERE ignored_at IS NULL) purchase_total_rmb,
 sum(shipping_rmb) FILTER(WHERE ignored_at IS NULL) shipping_total_rmb FROM purchase_items GROUP BY purchase_batch_id) i ON i.purchase_batch_id=b.id;

